export function articleImage(article: LearningArticle) {
  if (article.kind === 'life') return thinkerPortrait(article.philosopher);
  const image = illustrations.find((i) => i.key === article.philosopher);
  if (!image) throw new Error('Missing reviewed learning image');
  return image;
}

export function articleCredits(article: LearningArticle): string {
  const image = articleImage(article);
  const caption = 'caption' in image ? image.caption : image.note;
  return [
    '더 읽기 · 자료 출처',
    ...article.references,
    `이미지 안내\n${caption}\n${image.creator}\n${image.sourceUrl}\n${image.license}\n${image.licenseUrl}\n${image.changes}`,
    '본문은 원전과 연구 자료를 참고해 새로 작성한 해설이며 직접 인용문이 아닙니다.',
  ].join('\n\n');
}
